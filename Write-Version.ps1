<#
.SYNOPSIS
    Writes Version.h, the version of the plugin and of the GUI, from Version.txt and git.

.DESCRIPTION
    Version.txt holds the release number, MAJOR.MINOR.PATCH (e.g. 2.1.0): raise PATCH for a bug fix,
    MINOR for a new feature, and tag the release commit "v<number>".
    The 4th number is the count of commits since that tag (or, before the tag exists, since the
    last commit that changed Version.txt), so every commit gets its own number:
        2.1.0             the tagged commit, built from clean files
        2.1.0.3-g22f99dd  three commits later
        ...-dirty         built with changes that are not committed
    Both projects run this script before they build (Version.targets). Version.h is only rewritten
    when its content changes, so an unchanged version does not rebuild anything.
#>
param([string]$Root = $PSScriptRoot)

$ErrorActionPreference = 'Stop'
$number = (Get-Content -LiteralPath (Join-Path $Root 'Version.txt') -TotalCount 1).Trim()
if ($number -notmatch '^(\d+)\.(\d+)\.(\d+)$') { throw "Version.txt: expected MAJOR.MINOR.PATCH, found '$number'" }
$major = [int]$Matches[1]; $minor = [int]$Matches[2]; $patch = [int]$Matches[3]

function Invoke-Git { $ErrorActionPreference = 'Continue'; $out = & git.exe -C $Root @args 2>$null; if ($LASTEXITCODE -ne 0) { return $null }; $out }

$build = 0
$commit = 'unknown'
$dirty = $false
$head = Invoke-Git rev-parse --short=7 HEAD
if ($head) {
    $commit = "g$head"
    $described = Invoke-Git describe --tags --match "v$number" --long
    if ($described -match '-(\d+)-g[0-9a-f]+$') {
        $build = [int]$Matches[1]
    }
    else {
        $base = Invoke-Git log -1 --format=%H -- Version.txt
        if ($base) { $build = [int](Invoke-Git rev-list --count "$base..HEAD") }
    }
    $dirty = [bool](Invoke-Git status --porcelain --untracked-files=no)
}

$text = if ($build -eq 0 -and -not $dirty -and $head) { $number } else { "$number.$build-$commit" }
if ($dirty) { $text += '-dirty' }

$header = @"
// Generated by Write-Version.ps1 from Version.txt and git before each build: do not edit, not committed.
#pragma once
#define FFB_VERSION_MAJOR $major
#define FFB_VERSION_MINOR $minor
#define FFB_VERSION_PATCH $patch
#define FFB_VERSION_BUILD $build
#define FFB_VERSION_COMMIT "$commit"
#define FFB_VERSION_FILE "$number.$build"
#define FFB_VERSION_STRING "$text"
"@ -replace "`r?`n", "`r`n"

$target = Join-Path $Root 'Version.h'
$old = if (Test-Path -LiteralPath $target) { [IO.File]::ReadAllText($target) } else { '' }
if ($old -ne "$header`r`n") {
    [IO.File]::WriteAllText($target, "$header`r`n", (New-Object Text.UTF8Encoding $false))
    "Version.h: $text"
}
